def get_text(key: str, language: str = DEFAULT_LANGUAGE) -> str:
    """Return translated text, falling back to Uzbek."""
    language = language.strip().lower()

    translations = TEXTS.get(key)
    if translations is None:
        return key

    return translations.get(
        language,
        translations.get(DEFAULT_LANGUAGE, key),
    )


def get_language_name(language: str) -> str:
    """Return a language's display name."""
    return LANGUAGES.get(
        language.strip().lower(),
        LANGUAGES[DEFAULT_LANGUAGE],
    )


def get_language_keyboard_rows(
    languages_per_row: int = 2,
) -> list[list[tuple[str, str]]]:
    """Return language buttons grouped into rows."""
    if languages_per_row < 1:
        raise ValueError("languages_per_row kamida 1 bo‘lishi kerak")

    languages = list(LANGUAGES.items())
    return [
        languages[index:index + languages_per_row]
        for index in range(0, len(languages), languages_per_row)
]
    
